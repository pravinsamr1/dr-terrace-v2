/**
 * Helper to get the 6-digit pincode for a given area name (case-insensitive & whitespace-trimmed).
 * Returns undefined if no mapping exists.
 */
export function getPincodeForArea(areaName) {
  if (!areaName || typeof areaName !== 'string') return undefined;
  const trimmed = areaName.trim().toLowerCase();
  
  // Exact match first
  for (const [name, pin] of Object.entries(AREA_PINCODES)) {
    if (name.toLowerCase() === trimmed) {
      return pin;
    }
  }

  // Fallback: Check if area name matches without parenthetical suffix, e.g. 'Arani (Thiruvallur)' -> 'Arani'
  const baseName = trimmed.replace(/\s*\([^)]*\)/g, '').trim();
  if (baseName && baseName !== trimmed) {
    for (const [name, pin] of Object.entries(AREA_PINCODES)) {
      if (name.toLowerCase().replace(/\s*\([^)]*\)/g, '').trim() === baseName) {
        return pin;
      }
    }
  }

  return undefined;
}
